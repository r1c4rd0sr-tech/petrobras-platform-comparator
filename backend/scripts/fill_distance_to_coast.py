def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Distância haversine entre dois pontos geográficos, em km."""
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def nearest_coast_distance_km(lat: float, lon: float) -> float:
    """Distância (km) até o ponto de litoral de referência mais próximo."""
    return min(haversine_km(lat, lon, clat, clon) for clat, clon in COASTLINE)


def main() -> None:
    base = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "data", "platforms"))
    files = sorted(glob.glob(os.path.join(base, "part-*.json")))
    total_updated = 0
    for path in files:
        with open(path, encoding="utf-8") as fh:
            records = json.load(fh)
        changed = False
        for rec in records:
            if (
                rec.get("distance_to_coast_km") is None
                and rec.get("latitude") is not None
                and rec.get("longitude") is not None
            ):
                rec["distance_to_coast_km"] = round(
                    nearest_coast_distance_km(rec["latitude"], rec["longitude"]), 1
                )
                changed = True
                total_updated += 1
        if changed:
            with open(path, "w", encoding="utf-8") as fh:
                json.dump(records, fh, ensure_ascii=False, indent=2)
                fh.write("\n")
    print(f"Registros atualizados: {total_updated}")


if __name__ == "__main__":
    main()